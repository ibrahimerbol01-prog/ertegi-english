/** The four groups of the screen. The source's own part of speech is kept in the data. */
export const POS_GROUPS = ["noun", "verb", "adjective", "other"] as const;
export type PosGroup = (typeof POS_GROUPS)[number];
export const posGroup = (pos: string): PosGroup =>
  pos === "noun" || pos === "verb" || pos === "adjective" ? pos : "other";

/** The word a card stores and the voice reads: the first spelling of the headword ("colour/color" → "colour"). */
export const cardWord = (headword: string) => headword.split("/")[0].trim();

