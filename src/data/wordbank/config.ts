/* Wordbank «Сөздік қоры»: the word lists by CEFR level and part of speech.
   The data files next to this one (A1.json … C2.json) are generated by
   `npm run wordbank` (scripts/wordbank-build.mjs) from the sources below; do
   not edit them by hand. To add a source: put the file in the repo with its
   licence, add an entry here, run `npm run wordbank`. No imports, so the
   build script, the tests and the screen can all read it. */

export const WORDBANK_LEVELS = ["A1", "A2", "B1", "B2", "C1", "C2"] as const;
export type WordbankLevel = (typeof WORDBANK_LEVELS)[number];

export interface WordbankSource {
  /** Short id stamped on every word from this source. */
  id: string;
  /** CSV in the repo with the columns headword, pos, CEFR. */
  file: string;
  /** Levels taken from this source. */
  levels: readonly WordbankLevel[];
  /** Shown in the app under the list (required by the licence). */
  attribution: string;
  licence: string;
  url: string;
}

